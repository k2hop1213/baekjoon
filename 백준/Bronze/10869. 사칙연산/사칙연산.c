#include <stdio.h>

int main() {
    int A, B;

    // 두 자연수 A와 B 입력
    scanf("%d %d", &A, &B);

    // A+B 출력
    printf("%d\n", A + B);

    // A-B 출력
    printf("%d\n", A - B);

    // A*B 출력
    printf("%d\n", A * B);

    // A/B 출력
    printf("%d\n", A / B);

    // A%B 출력
    printf("%d\n", A % B);

    return 0;
}
